/**
 * Generates docs/status.md from the Vitest JSON results: which requirement IDs have passing
 * tagged tests. Run via `pnpm status`. A requirement is only "tested" here; whether its
 * acceptance criterion is fully covered is a human call recorded in the spec.
 */
import { readFileSync, writeFileSync } from "node:fs";

interface AssertionResult {
  title: string;
  status: string;
}
interface Json {
  testResults: { assertionResults: AssertionResult[] }[];
}

const json = JSON.parse(readFileSync("test-results/vitest.json", "utf8")) as Json;
const byTag = new Map<string, { pass: number; fail: number }>();

for (const file of json.testResults) {
  for (const t of file.assertionResults) {
    for (const [, tag] of t.title.matchAll(/\[([A-Z0-9-]+)\]/g)) {
      if (!tag) continue;
      const entry = byTag.get(tag) ?? { pass: 0, fail: 0 };
      if (t.status === "passed") entry.pass++;
      else entry.fail++;
      byTag.set(tag, entry);
    }
  }
}

const rows = [...byTag.entries()]
  .sort(([a], [b]) => a.localeCompare(b))
  .map(([tag, r]) => `| ${tag} | ${r.pass} | ${r.fail} | ${r.fail === 0 ? "passing" : "FAILING"} |`);

writeFileSync(
  "docs/status.md",
  [
    "# Test status by requirement tag",
    "",
    "Generated by `pnpm status` from the Vitest results. Do not edit by hand.",
    "Covers Vitest only; pgTAP and Playwright results are in CI.",
    "A passing tag means tests exist and pass, not that the requirement's acceptance criterion is fully met.",
    "",
    "| Tag | Passed | Failed | State |",
    "|---|---|---|---|",
    ...rows,
    "",
  ].join("\n"),
);
console.log(`docs/status.md: ${byTag.size} tags`);
